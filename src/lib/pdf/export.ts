// src/lib/pdf/export.ts

import { jsPDF } from "jspdf";
import type { LLMOutput } from "@/types/llm-output";
import type { Template } from "@/types/document";

/**
 * Generate a clean, professional PDF from an LLMOutput.
 * Client-side only — no server round-trip.
 */
export function exportDocumentAsPdf(params: {
  output: LLMOutput;
  template: Template;
  branding?: { businessName?: string };
}): void {
  const { output, template, branding } = params;

  const doc = new jsPDF({
    unit: "pt",
    format: "letter",
    orientation: "portrait",
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 56; // ~0.78"
  const contentWidth = pageWidth - margin * 2;
  let cursorY = margin;

  // Helper: if the next block would overflow, add a new page
  function ensureSpace(height: number) {
    if (cursorY + height > pageHeight - margin) {
      doc.addPage();
      cursorY = margin;
    }
  }

  // Header: business name if provided, else template name
  const headerText = branding?.businessName?.trim() || "DictaDoc";
  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(120, 120, 120);
  doc.text(headerText, margin, cursorY);
  cursorY += 24;

  // Horizontal rule
  doc.setDrawColor(220, 220, 220);
  doc.setLineWidth(0.5);
  doc.line(margin, cursorY, pageWidth - margin, cursorY);
  cursorY += 24;

  // Title
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(30, 30, 30);
  const titleLines = doc.splitTextToSize(output.metadata.title, contentWidth);
  for (const line of titleLines) {
    ensureSpace(24);
    doc.text(line, margin, cursorY);
    cursorY += 24;
  }

  // Subject (if present)
  if (output.metadata.subject) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);
    doc.setTextColor(90, 90, 90);
    const subjectLines = doc.splitTextToSize(output.metadata.subject, contentWidth);
    for (const line of subjectLines) {
      ensureSpace(16);
      doc.text(line, margin, cursorY);
      cursorY += 16;
    }
  }

  cursorY += 12;

  // Sections
  for (const section of output.sections) {
    ensureSpace(40);

    // Section heading
    doc.setFont("helvetica", "bold");
    doc.setFontSize(12);
    doc.setTextColor(30, 30, 30);
    const headingLines = doc.splitTextToSize(section.heading, contentWidth);
    for (const line of headingLines) {
      ensureSpace(18);
      doc.text(line, margin, cursorY);
      cursorY += 18;
    }

    cursorY += 4;

    // Section body
    doc.setFont("helvetica", "normal");
    doc.setFontSize(10.5);
    doc.setTextColor(50, 50, 50);
    const bodyLines = doc.splitTextToSize(section.body, contentWidth);
    for (const line of bodyLines) {
      ensureSpace(15);
      doc.text(line, margin, cursorY);
      cursorY += 15;
    }

    cursorY += 14;
  }

  // Footer on every page
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont("helvetica", "normal");
    doc.setFontSize(8);
    doc.setTextColor(150, 150, 150);
    const footer = `Generated by DictaDoc — ${new Date().toLocaleDateString()}`;
    doc.text(footer, margin, pageHeight - 28);
    doc.text(
      `Page ${i} of ${totalPages}`,
      pageWidth - margin - 40,
      pageHeight - 28
    );
  }

  // Filename
  const date = new Date().toISOString().slice(0, 10);
  const subjectSlug = output.metadata.subject
    ? "-" + output.metadata.subject.toLowerCase().replace(/[^a-z0-9]+/g, "-").slice(0, 30)
    : "";
  const filename = `${template.filenameStem}-${date}${subjectSlug}.pdf`;

  doc.save(filename);
}
